const sdkImport = "github.com/invertase/reeval/sdks/go/reeval"

// mainDir is the generated main package's directory inside the eval package's, which exists
// only in the build's overlay.
const mainDir = "reeval_eval_main"

var evalName = regexp.MustCompile(`^Eval($|[^a-z])`)

type listed struct {
	Dir        string
	ImportPath string
	Name       string
	GoFiles    []string
	Error      *struct{ Err string }
}

func goCommand() string {
	if g := os.Getenv("REEVAL_GO"); g != "" {
		return g
	}
	return "go"
}

// build compiles the eval program for the package in dir, relative to the project root.
func (d *driver) build(dir string) (*child, error) {
	list := exec.Command(goCommand(), "list", "-json", "./"+dir)
	list.Dir = d.root
	var stderr bytes.Buffer
	list.Stderr = &stderr
	out, err := list.Output()
	if err != nil {
		return nil, fmt.Errorf("go list ./%s failed: %s", dir, strings.TrimSpace(stderr.String()+" "+err.Error()))
	}
	var pkg listed
	if err := json.Unmarshal(out, &pkg); err != nil {
		return nil, fmt.Errorf("go list ./%s: %w", dir, err)
	}
	if pkg.Error != nil {
		return nil, errors.New(pkg.Error.Err)
	}
	if pkg.Name == "main" {
		return nil, fmt.Errorf("%s is package main, which a program can't import: eval files go in "+
			"a package of their own, such as package evals", dir)
	}
	evals, err := discover(d.root, pkg)
	if err != nil {
		return nil, err
	}
	src := generate(pkg.ImportPath, evals)
	n := strconv.Itoa(len(d.packages) + 1)
	gen := filepath.Join(d.tmp, "main"+n+".go")
	if err := os.WriteFile(gen, src, 0o644); err != nil {
		return nil, err
	}
	overlay, _ := json.Marshal(map[string]any{"Replace": map[string]string{
		filepath.Join(pkg.Dir, mainDir, "main.go"): gen,
	}})
	overlayFile := filepath.Join(d.tmp, "overlay"+n+".json")
	if err := os.WriteFile(overlayFile, overlay, 0o644); err != nil {
		return nil, err
	}
	bin := filepath.Join(d.tmp, "evals"+n)
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	cmd := exec.Command(goCommand(), "build", "-overlay", overlayFile, "-o", bin, "./"+mainDir)
	cmd.Dir = pkg.Dir
	var built bytes.Buffer
	cmd.Stdout, cmd.Stderr = &built, &built
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("%s doesn't build:\n%s", dir, strings.TrimSpace(built.String()))
	}
	return d.spawn(dir, bin)
}

type found struct {
	file, name string
}

// discover finds the package's EvalXxx functions, as go test finds TestXxx: in its _eval.go
// files, in source order.
func discover(root string, pkg listed) ([]found, error) {
	var evals []found
	for _, name := range pkg.GoFiles {
		if !strings.HasSuffix(name, "_eval.go") {
			continue
		}
		file := filepath.Join(pkg.Dir, name)
		f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		rel, err := filepath.Rel(root, file)
		if err != nil {
			return nil, err
		}
		sdk := importName(f)
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || !evalName.MatchString(fn.Name.Name) {
				continue
			}
			if !takesE(fn, sdk) {
				return nil, fmt.Errorf("%s: wrong signature for %s, must be: func %s(e *reeval.E)",
					filepath.ToSlash(rel), fn.Name.Name, fn.Name.Name)
			}
			evals = append(evals, found{file: filepath.ToSlash(rel), name: fn.Name.Name})
		}
	}
	return evals, nil
}

func importName(f *ast.File) string {
	for _, spec := range f.Imports {
		if p, _ := strconv.Unquote(spec.Path.Value); p == sdkImport {
			if spec.Name != nil {
				return spec.Name.Name
			}
			return "reeval"
		}
	}
	return ""
}

func takesE(fn *ast.FuncDecl, sdk string) bool {
	t := fn.Type
	if sdk == "" || t.TypeParams != nil || t.Results != nil || len(t.Params.List) != 1 || len(t.Params.List[0].Names) > 1 {
		return false
	}
	star, ok := t.Params.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	sel, ok := star.X.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	x, ok := sel.X.(*ast.Ident)
	return ok && x.Name == sdk && sel.Sel.Name == "E"
}

func generate(importPath string, evals []found) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by reeval-runner. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"os\"\n\n")
	fmt.Fprintf(&b, "\treeval %q\n", sdkImport)
	if len(evals) > 0 {
		fmt.Fprintf(&b, "\tevals %q\n", importPath)
	} else {
		fmt.Fprintf(&b, "\t_ %q\n", importPath)
	}
	b.WriteString(")\n\nfunc main() {\n\tos.Exit(reeval.MainStart([]reeval.InternalEval{\n")
	for _, e := range evals {
		fmt.Fprintf(&b, "\t\t{File: %q, Name: %q, F: evals.%s},\n", e.file, e.name, e.name)
	}
	b.WriteString("\t}).Run())\n}\n")
	return b.Bytes()
}

// child is one package's eval program.
type child struct {
	d     *driver
	dir   string
	cmd   *exec.Cmd
	stdin io.WriteCloser

	mu         sync.Mutex
	gone       bool
	collecting chan struct{}
}

func (d *driver) spawn(dir, bin string) (*child, error) {
	cmd := exec.Command(bin)
	cmd.Dir = d.root
	cmd.Env = append(os.Environ(), "REEVAL_RUNNER=stdio", "REEVAL_RUNNER_PROTOCOL="+strconv.Itoa(reeval.RunnerProtocol))
	cmd.Stderr = os.Stderr
	stdin, err := cmd.StdinPipe()
	if err != nil {
		return nil, err
	}
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return nil, err
	}
	if err := cmd.Start(); err != nil {
		return nil, err
	}
	c := &child{d: d, dir: dir, cmd: cmd, stdin: stdin}
	go c.read(stdout)
	return c, nil
}

func (c *child) send(line []byte) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if !c.gone {
		_, _ = c.stdin.Write(append(line, '\n'))
	}
}

type childHead struct {
	T    string  `json:"t"`
	Type string  `json:"type"`
	Key  *string `json:"key"`
}

func (c *child) read(stdout io.Reader) {
	scanner := bufio.NewScanner(stdout)
	scanner.Buffer(make([]byte, 64*1024), 64*1024*1024)
	for scanner.Scan() {
		line := append([]byte(nil), scanner.Bytes()...)
		var h childHead
		if err := json.Unmarshal(line, &h); err != nil {
			fmt.Fprintf(os.Stderr, "%s\n", line)
			continue
		}
		switch {
		case h.T == "hello":
			continue
		case h.T == "declared" || h.T == "load-error":
			c.d.write(line)
			c.answered()
			continue
		case h.Type == "done" && h.Key != nil:
			c.d.mu.Lock()
			delete(c.d.keys, *h.Key)
			c.d.mu.Unlock()
		}
		c.d.write(line)
	}
	err := c.cmd.Wait()
	c.mu.Lock()
	c.gone = true
	c.mu.Unlock()
	reason := "it exited"
	if err != nil {
		reason = err.Error()
	}
	message := fmt.Sprintf("the eval program for %s stopped: %s", c.dir, reason)
	if c.answered() {
		c.d.send(map[string]any{"t": "load-error", "error": map[string]any{"name": "InfraError", "message": message}})
	}
	c.d.mu.Lock()
	var keys []string
	for key, owner := range c.d.keys {
		if owner == c {
			keys = append(keys, key)
			delete(c.d.keys, key)
		}
	}
	c.d.mu.Unlock()
	for _, key := range keys {
		c.d.send(map[string]any{"type": "done", "key": key, "error": map[string]any{"name": "InfraError", "message": message}})
	}
}

// answered ends the collect waiting on this program, reporting whether there was one.
func (c *child) answered() bool {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.collecting == nil {
		return false
	}
	close(c.collecting)
	c.collecting = nil
	return true
}

func (c *child) stop() {
	c.mu.Lock()
	defer c.mu.Unlock()
	if !c.gone {
		_ = c.stdin.Close()
	}
}
