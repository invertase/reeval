// Command gensums writes the launcher's sums.go from a release's binaries and their SHA256SUMS,
// so the module tagged for that release pins each target's binary by sha256 and size:
//
//	go run ./internal/gensums <version> <directory of the release's files> cmd/reeval/sums.go
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

var targets = []string{
	"darwin-arm64", "darwin-x64", "linux-arm64", "linux-arm64-musl",
	"linux-x64", "linux-x64-baseline", "linux-x64-musl", "linux-x64-musl-baseline",
	"windows-x64", "windows-x64-baseline",
}

var hexSum = regexp.MustCompile(`^[0-9a-f]{64}$`)

// render is sums.go for version's binaries in dir, every target's listed in dir's SHA256SUMS and
// hashing to what it lists.
func render(version, dir string) ([]byte, error) {
	sums, err := os.ReadFile(filepath.Join(dir, "SHA256SUMS"))
	if err != nil {
		return nil, err
	}
	found := map[string]string{}
	scanner := bufio.NewScanner(bytes.NewReader(sums))
	for scanner.Scan() {
		f := strings.Fields(scanner.Text())
		if len(f) != 2 {
			continue
		}
		name := strings.TrimPrefix(f[1], "*")
		if strings.HasPrefix(name, "reeval-"+version+"-") {
			sum := strings.ToLower(f[0])
			if !hexSum.MatchString(sum) {
				return nil, fmt.Errorf("%s's sum %q isn't a sha256", name, f[0])
			}
			found[name] = sum
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/gensums from a release's binaries. DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("// sumsVersion is the reeval release releaseBinaries records; empty in a commit that isn't a\n")
	b.WriteString("// release, whose launcher checks a download against the release's SHA256SUMS alone.\n")
	fmt.Fprintf(&b, "var sumsVersion = %q\n\nvar releaseBinaries = map[string]binary{\n", version)
	var missing []string
	for _, t := range targets {
		name := "reeval-" + version + "-" + t
		if strings.HasPrefix(t, "windows") {
			name += ".exe"
		}
		sum, ok := found[name]
		if !ok {
			missing = append(missing, name)
			continue
		}
		delete(found, name)
		size, actual, err := measure(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		if actual != sum {
			return nil, fmt.Errorf("%s's sha256 is %s, but SHA256SUMS lists %s", name, actual, sum)
		}
		fmt.Fprintf(&b, "\t%q: {sha256: %q, size: %d},\n", name, sum, size)
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("SHA256SUMS doesn't list %s", strings.Join(missing, ", "))
	}
	if len(found) > 0 {
		extra := make([]string, 0, len(found))
		for name := range found {
			extra = append(extra, name)
		}
		slices.Sort(extra)
		return nil, fmt.Errorf("SHA256SUMS lists binaries for no known target: %s", strings.Join(extra, ", "))
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

// measure is a file's size and sha256.
func measure(path string) (int64, string, error) {
	f, err := os.Open(path)
	if err != nil {
		return 0, "", err
	}
	defer f.Close()
	h := sha256.New()
	size, err := io.Copy(h, f)
	if err != nil {
		return 0, "", err
	}
	return size, hex.EncodeToString(h.Sum(nil)), nil
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gensums <version> <release directory> <sums.go>")
		os.Exit(2)
	}
	out, err := render(strings.TrimPrefix(os.Args[1], "v"), os.Args[2])
	if err == nil {
		err = os.WriteFile(os.Args[3], out, 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "gensums:", err)
		os.Exit(1)
	}
}
