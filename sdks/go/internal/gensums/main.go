// Command gensums writes the launcher's sums.go from a release's SHA256SUMS, so the module
// tagged for that release pins each target's binary:
//
//	go run ./internal/gensums <version> <SHA256SUMS> cmd/reeval/sums.go
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strings"
)

var targets = []string{
	"darwin-arm64", "darwin-x64", "linux-arm64", "linux-arm64-musl",
	"linux-x64", "linux-x64-musl", "windows-x64",
}

var hexSum = regexp.MustCompile(`^[0-9a-f]{64}$`)

// render is sums.go for version's binaries, every target's listed in sums.
func render(version string, sums []byte) ([]byte, error) {
	found := map[string]string{}
	scanner := bufio.NewScanner(bytes.NewReader(sums))
	for scanner.Scan() {
		f := strings.Fields(scanner.Text())
		if len(f) != 2 {
			continue
		}
		name := strings.TrimPrefix(f[1], "*")
		if strings.HasPrefix(name, "reeval-"+version+"-") {
			sum := strings.ToLower(f[0])
			if !hexSum.MatchString(sum) {
				return nil, fmt.Errorf("%s's sum %q isn't a sha256", name, f[0])
			}
			found[name] = sum
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/gensums from a release's SHA256SUMS. DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("// sumsVersion is the reeval release whose binaries' sha256 are releaseSums; empty in a commit\n")
	b.WriteString("// that isn't a release, whose launcher reads the release's SHA256SUMS instead.\n")
	fmt.Fprintf(&b, "var sumsVersion = %q\n\nvar releaseSums = map[string]string{\n", version)
	var missing []string
	for _, t := range targets {
		name := "reeval-" + version + "-" + t
		if strings.HasPrefix(t, "windows") {
			name += ".exe"
		}
		sum, ok := found[name]
		if !ok {
			missing = append(missing, name)
			continue
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", name, sum)
		delete(found, name)
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("SHA256SUMS doesn't list %s", strings.Join(missing, ", "))
	}
	if len(found) > 0 {
		extra := make([]string, 0, len(found))
		for name := range found {
			extra = append(extra, name)
		}
		slices.Sort(extra)
		return nil, fmt.Errorf("SHA256SUMS lists binaries for no known target: %s", strings.Join(extra, ", "))
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gensums <version> <SHA256SUMS> <sums.go>")
		os.Exit(2)
	}
	sums, err := os.ReadFile(os.Args[2])
	if err == nil {
		var out []byte
		if out, err = render(strings.TrimPrefix(os.Args[1], "v"), sums); err == nil {
			err = os.WriteFile(os.Args[3], out, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "gensums:", err)
		os.Exit(1)
	}
}
