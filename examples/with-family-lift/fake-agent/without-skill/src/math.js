export function add(a, b) {
  return a + b
}

export function subtract(a, b) {
  return a - b
}

export function multiply(a, b) {
  return a * b
}

export function divide(a, b) {
  return a / b
}

export function power(a, b) {
  return a ** b
}

export function max(a, b) {
  return Math.max(a, b)
}

export function min(a, b) {
  return Math.min(a, b)
}
