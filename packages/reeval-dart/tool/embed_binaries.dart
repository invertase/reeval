// Writes lib/src/binaries.g.dart from a reeval release's binaries and its
// SHA256SUMS, so the launcher checks the binary it downloads against the sha256
// and size published in the package rather than against the release's own
// SHA256SUMS alone. Run it before `dart pub publish`, on a directory holding
// the release of this package's version:
//
//   dart run tool/embed_binaries.dart path/to/release
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:reeval/src/version.dart';

const _targets = [
  'linux-x64',
  'linux-x64-baseline',
  'linux-arm64',
  'linux-x64-musl',
  'linux-x64-musl-baseline',
  'linux-arm64-musl',
  'darwin-x64',
  'darwin-arm64',
  'windows-x64',
  'windows-x64-baseline',
];

Never fail(String message) {
  stderr.writeln(message);
  exit(1);
}

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/embed_binaries.dart <release dir>');
    exit(2);
  }
  final dir = Directory(args.single);
  final sumsFile = File('${dir.path}/SHA256SUMS');
  if (!sumsFile.existsSync()) fail('${dir.path} has no SHA256SUMS');
  final sums = <String, String>{};
  for (final line in sumsFile.readAsLinesSync()) {
    final match = RegExp(r'^([0-9a-fA-F]{64})\s+\*?(\S+)\s*$').firstMatch(line);
    if (match != null) sums[match[2]!] = match[1]!.toLowerCase();
  }
  final binaries = <String, ({String sha256, int size})>{};
  for (final target in _targets) {
    final exe = target.startsWith('windows') ? '.exe' : '';
    final asset = 'reeval-$packageVersion-$target$exe';
    final listed =
        sums[asset] ?? fail('${sumsFile.path} has no entry for $asset');
    final file = File('${dir.path}/$asset');
    if (!file.existsSync()) fail('${dir.path} has no $asset');
    final bytes = file.readAsBytesSync();
    final actual = sha256.convert(bytes).toString();
    if (actual != listed) {
      fail('${file.path} has sha256 $actual, but SHA256SUMS says $listed');
    }
    binaries[target] = (sha256: actual, size: bytes.length);
  }
  final out = File.fromUri(
    Platform.script.resolve('../lib/src/binaries.g.dart'),
  );
  out.writeAsStringSync('''
// Generated by tool/embed_binaries.dart from a release's binaries and
// SHA256SUMS when the package is published. Do not edit.

/// The reeval version [releasedBinaries] describes.
const binariesVersion = '$packageVersion';

/// The sha256 and size of reeval's binary for each target, by target.
const releasedBinaries = <String, ({String sha256, int size})>{
${[for (final MapEntry(:key, :value) in binaries.entries) "  '$key': (\n    sha256: '${value.sha256}',\n    size: ${value.size},\n  ),"].join('\n')}
};
''');
  stdout.writeln('wrote ${out.path}');
}
