// Writes lib/src/binaries.g.dart from a reeval release's SHA256SUMS, so the
// launcher checks the binary it downloads against hashes published in the
// package rather than against the release's own SHA256SUMS. Run it before
// `dart pub publish`, with the release of this package's version:
//
//   dart run tool/embed_binaries.dart path/to/SHA256SUMS
import 'dart:io';

import 'package:reeval/src/version.dart';

const _targets = [
  'linux-x64',
  'linux-arm64',
  'linux-x64-musl',
  'linux-arm64-musl',
  'darwin-x64',
  'darwin-arm64',
  'windows-x64',
];

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/embed_binaries.dart <SHA256SUMS>');
    exit(2);
  }
  final sums = <String, String>{};
  for (final line in File(args.single).readAsLinesSync()) {
    final match = RegExp(r'^([0-9a-fA-F]{64})\s+\*?(\S+)\s*$').firstMatch(line);
    if (match != null) sums[match[2]!] = match[1]!.toLowerCase();
  }
  final hashes = <String, String>{};
  for (final target in _targets) {
    final exe = target.startsWith('windows') ? '.exe' : '';
    final asset = 'reeval-$packageVersion-$target$exe';
    final hash = sums[asset];
    if (hash == null) {
      stderr.writeln('${args.single} has no entry for $asset');
      exit(1);
    }
    hashes[target] = hash;
  }
  final out = File.fromUri(
    Platform.script.resolve('../lib/src/binaries.g.dart'),
  );
  out.writeAsStringSync('''
// Generated by tool/embed_binaries.dart from a release's SHA256SUMS when the
// package is published. Do not edit.

/// The reeval version [binarySha256] has hashes for.
const binariesVersion = '$packageVersion';

/// The sha256 of reeval's binary for each target, by target.
const binarySha256 = <String, String>{
${[for (final MapEntry(:key, :value) in hashes.entries) "  '$key':\n      '$value',"].join('\n')}
};
''');
  stdout.writeln('wrote ${out.path}');
}
