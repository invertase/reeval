// Writes src/pi-provider-table.ts: runs probe.mjs in the pinned pi's sandbox image and lists each
// provider whose key pi sends in a header on a fixed host, with the requests it was seen to send
// it on, and every other provider with the reason reeval refuses it.
//
//   node scripts/provider-table.mjs [image]    (default: reeval-sandbox:pi-<package version>)
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const { version } = JSON.parse(readFileSync(`${root}package.json`, 'utf8'))
const image = process.argv[2] ?? `reeval-sandbox:pi-${version}`
const BOOTSTRAP = '/home/reeval/.ai-sdk-harness/.harness-bootstrap/pi'

/** Why a provider can't run, where the probe can't tell. */
const REASONS = {
  'google-vertex':
    'it authenticates with Application Default Credentials, not a key: run it on vertex()',
  openrouter: "it's a gateway: run the model on openrouter()",
  'vercel-ai-gateway': "it's a gateway: run the model on vercel()",
  'amazon-bedrock': 'it signs its requests with AWS credentials, not a key in a header',
  'github-copilot': 'it runs on a GitHub Copilot subscription, through a GitHub login',
  'openai-codex': 'it runs on a ChatGPT subscription, through a ChatGPT login',
}

const probe = JSON.parse(
  execFileSync(
    'docker',
    [
      ...['run', '--rm', '--network', 'none', '-v', `${root}scripts:/probe:ro`],
      ...['--entrypoint', 'node', image, '/probe/probe.mjs', BOOTSTRAP],
    ],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  ),
)

/** The request's path as an endpoint: Gemini's names the model, so it's a pattern. */
const pathOf = (url) => {
  const path = url.replace(/\?.*$/, '')
  const gemini = /^(.*\/models\/)[^/]+(:streamGenerateContent)$/.exec(path)
  return gemini ? { regex: `^${gemini[1]}[^/]+${gemini[2]}$` } : { exact: path }
}

const supported = []
const refused = []
for (const { provider: id, env, apis } of probe.providers) {
  const endpoints = apis.flatMap(({ api, baseUrl, requests }) =>
    requests
      .filter((r) => r.headers.length)
      .map((r) => ({
        host: new URL(baseUrl).hostname,
        method: [r.method],
        path: pathOf(r.url),
        api,
        headers: r.headers.map(({ name, scheme }) => (scheme ? { name, scheme } : { name })),
      })),
  )
  const unique = [...new Map(endpoints.map((e) => [JSON.stringify(e), e])).values()]
  let reason = REASONS[id]
  if (!reason && !env) reason = 'pi reads no key for it from a variable'
  if (!reason && !apis.length) reason = "pi's catalog has no chat model for it"
  if (!reason && apis.some((a) => !a.baseUrl || /[{}$]/.test(a.baseUrl))) {
    reason = "its host is your account's or resource's, which pi takes from more variables"
  }
  if (!reason && !unique.length) reason = 'the probe saw pi send its key nowhere'
  if (reason) refused.push({ id, reason })
  else supported.push({ id, credentialEnv: env, endpoints: unique })
}
const byId = (a, b) => a.id.localeCompare(b.id)

writeFileSync(
  `${root}src/pi-provider-table.ts`,
  `// Generated by scripts/provider-table.mjs from a probe of pi-ai ${probe.piAi} (scripts/probe.mjs):
// don't edit by hand. Regenerate it on a pi bump.
import type { PiProvider, RefusedPiProvider } from './pi-providers.ts'

/** The pi-ai version the table was probed on; a test holds it to the lockfile's. */
export const PROBED_VERSION = ${JSON.stringify(probe.piAi)}

/** Every provider whose key pi sends in a header on a fixed host, as the probe saw it. */
export const PI_PROVIDERS: readonly PiProvider[] = [
${supported
  .sort(byId)
  .map((p) => `  ${JSON.stringify(p)},`)
  .join('\n')}
]

/** Every other provider of pi's, and why reeval can't run it on its own key. */
export const PI_REFUSED_PROVIDERS: readonly RefusedPiProvider[] = [
${refused
  .sort(byId)
  .map((p) => `  ${JSON.stringify(p)},`)
  .join('\n')}
]
`,
)
console.log(`${supported.length} providers, ${refused.length} refused`)
