// Writes src/prices.ts: list prices per million tokens for the models reeval's harnesses and
// judges run, from models.dev's direct providers, plus Cursor's own models from its pricing page.
// `reeval run --dry-run` prices its cost estimate with it, so it carries the date it was fetched.
//
//   pnpm --filter reeval prices:update
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE = 'https://models.dev/api.json'
/** The providers whose own API a harness or judge calls, first one wins on a shared id. */
const PROVIDERS = ['anthropic', 'openai', 'google', 'xai']
/** Cursor's models aren't on models.dev: https://cursor.com/docs/models-and-pricing */
const CURSOR: Record<string, Price> = {
  'composer-2.5': [0.5, 0.2, 0.5, 2.5],
  'composer-2.5-fast': [3, 0.5, 3, 15],
}

/** Input, cache read, cache write, output. */
type Price = [number, number, number, number]
type Model = {
  tool_call?: boolean
  status?: string
  cost?: { input?: number; output?: number; cache_read?: number; cache_write?: number }
}

const out = join(fileURLToPath(new URL('..', import.meta.url)), 'src', 'prices.ts')
const catalog = (await (await fetch(SOURCE)).json()) as Record<
  string,
  { models: Record<string, Model> }
>
const prices: Record<string, Price> = {}
for (const provider of PROVIDERS) {
  const models = catalog[provider]?.models
  if (!models) throw new Error(`${SOURCE} has no ${provider} provider`)
  for (const [id, m] of Object.entries(models).sort(([a], [b]) => a.localeCompare(b))) {
    const c = m.cost
    if (!m.tool_call || m.status === 'deprecated' || c?.input == null || c.output == null) continue
    prices[id] ??= [c.input, c.cache_read ?? c.input, c.cache_write ?? c.input, c.output]
  }
}
Object.assign(prices, CURSOR)

const date = new Date().toISOString().slice(0, 10)
const rows = Object.entries(prices)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, p]) => `  '${id}': [${p.join(', ')}],`)
writeFileSync(
  out,
  [
    '// Generated by scripts/prices.ts (`pnpm --filter reeval prices:update`); do not edit.',
    '',
    `/** The day these list prices were fetched. */`,
    `export const PRICES_DATE = '${date}'`,
    `export const PRICES_SOURCE = 'models.dev and cursor.com/docs/models-and-pricing'`,
    '',
    '/** USD per million tokens, by model id: input, cache read, cache write, output. */',
    'export const PRICES: Record<string, readonly [number, number, number, number]> = {',
    ...rows,
    '}',
    '',
  ].join('\n'),
)
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', out], { stdio: 'inherit' })
console.log(`wrote ${Object.keys(prices).length} prices to ${out}`)
